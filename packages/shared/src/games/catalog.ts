/**
 * Helper to fetch a game by its unique ID
 */
export function getGameById(id: GameId): GameMetadata | undefined {
  return GAMES_CATALOG.find((g) => g.id === id);
}

/**
 * Filter games by category and access tier
 */
export function filterGames(
  category: "all" | GameMetadata["category"],
  access: "all" | GameMetadata["access"],
  searchQuery: string = ""
): GameMetadata[] {
  return GAMES_CATALOG.filter((game) => {
    if (category !== "all" && game.category !== category) return false;
    if (access !== "all" && game.access !== access) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      const match =
        game.title.toLowerCase().includes(q) ||
        game.shortDescription.toLowerCase().includes(q) ||
        game.category.toLowerCase().includes(q) ||
        game.examRelevance.toLowerCase().includes(q);
      if (!match) return false;
    }
    return true;
  });
}
